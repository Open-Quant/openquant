BENCH_CALL = re.compile(r"""bench_function\(\s*"([^"]+)\"""")
GROUP_CALL = re.compile(r"""benchmark_group\(\s*"([^"]+)\"""")


def bench_sources() -> tuple[dict[str, str], list[tuple[str, str]]]:
    """Benchmark key -> bench file, and (name, file) for every group/function found."""
    by_key: dict[str, str] = {}
    found: list[tuple[str, str]] = []
    for path in sorted(BENCH_SRC.glob("*.rs")):
        text = path.read_text(encoding="utf-8")
        for name in BENCH_CALL.findall(text):
            by_key[name.replace("/", "_")] = path.name
            found.append((name, path.name))
        for name in GROUP_CALL.findall(text):
            found.append((f"{name}/*", path.name))
    return by_key, found


def render_performance(stamp: str) -> str:
    latest = json.loads((BENCH / "latest_benchmarks.json").read_text(encoding="utf-8"))
    baseline = json.loads((BENCH / "baseline_benchmarks.json").read_text(encoding="utf-8"))
    manifest = json.loads((BENCH / "benchmark_manifest.json").read_text(encoding="utf-8"))
    overrides = json.loads((BENCH / "threshold_overrides.json").read_text(encoding="utf-8"))
    data = json.loads((BENCH / "data_processing" / "latest.json").read_text(encoding="utf-8"))
    by_key, found = bench_sources()

    missing = [k for k in manifest if k not in BENCH_DESCRIPTIONS]
    if missing:
        raise SourceError(f"add a BENCH_DESCRIPTIONS entry in {SCRIPT} for: {', '.join(missing)}")
    unknown = [k for k in manifest if k not in by_key]
    if unknown:
        raise SourceError(f"manifest benchmarks with no bench_function in benches/: {unknown}")

    workflow = (ROOT / ".github" / "workflows" / "benchmark-regression.yml").read_text(
        encoding="utf-8"
    )
    m = re.search(r"--max-regression-pct\s+([0-9.]+)", workflow)
    if not m:
        raise SourceError("could not read --max-regression-pct from benchmark-regression.yml")
    gate_pct = float(m.group(1))  # the gate's default threshold, read from the workflow

    when = latest.get("generated_at_utc", "")[:10] or "unknown date"
    commit = latest.get("commit") or "unrecorded"
    commit_md = f"[`{commit}`]({REPO_URL}/commit/{commit})" if latest.get("commit") else commit

    out = [
        frontmatter(
            title="Performance",
            description=(
                "Committed criterion and Python benchmark results, what each benchmark "
                "measures, and how CI gates regressions."
            ),
            generated_from="benchmarks/",
            order=2,
            stamp=stamp,
        )
    ]
    out.append(
        "The numbers below are the benchmark results committed in `benchmarks/`. They are "
        "one run on one machine, and the files do not record which machine, so read them as "
        "orders of magnitude and relative costs, not as a promise about your hardware. Pull "
        "requests are not judged against them (see [Regression gate](#regression-gate)).\n"
    )
    out.append("## Rust core (criterion)\n")
    out.append(
        f"`benchmarks/latest_benchmarks.json`: {latest.get('count', len(latest['benchmarks']))} "
        f"benchmarks, collected on {when} at commit {commit_md}. Times are criterion's mean per "
        "iteration with its 95% confidence interval.\n"
    )
    rows = [
        "| Benchmark | What it measures | Mean (ms) | 95% CI (ms) | Source |",
        "| --- | --- | ---: | ---: | --- |",
    ]
    for key in sorted(latest["benchmarks"], key=lambda k: -latest["benchmarks"][k]["mean_ms"]):
        b = latest["benchmarks"][key]
        lo, hi = b["ci_lower_ns"] / 1e6, b["ci_upper_ns"] / 1e6
        src = by_key.get(key)
        src_md = (
            f"[`{src}`]({REPO_URL}/blob/main/crates/openquant/benches/{src})" if src else "—"
        )
        desc = BENCH_DESCRIPTIONS.get(key, "not in the manifest")
        rows.append(
            f"| `{key}` | {desc} | {fmt_ms(b['mean_ms'])} | "
            f"{fmt_ms(lo)}–{fmt_ms(hi)} | {src_md} |"
        )
    out.append("\n".join(rows) + "\n")

    same = latest["benchmarks"] == baseline["benchmarks"]
    if same:
        out.append(
            "`benchmarks/baseline_benchmarks.json` holds the same numbers: the baseline was "
            "last refreshed from this run.\n"
        )
    else:
        rows = ["| Benchmark | Baseline (ms) | Latest (ms) | Change |", "| --- | ---: | ---: | ---: |"]
        for key in sorted(set(baseline["benchmarks"]) & set(latest["benchmarks"])):
            b = baseline["benchmarks"][key]["mean_ms"]
            c = latest["benchmarks"][key]["mean_ms"]
            rows.append(f"| `{key}` | {fmt_ms(b)} | {fmt_ms(c)} | {(c - b) / b * 100:+.1f}% |")
        out.append(
            f"Against `benchmarks/baseline_benchmarks.json` (collected "
            f"{baseline.get('generated_at_utc', '')[:10] or 'on an unrecorded date'}):\n"
        )
        out.append("\n".join(rows) + "\n")

    not_tracked = [(n, f) for n, f in found if n.replace("/", "_") not in manifest]
    if not_tracked:
        items = ", ".join(f"`{n}` ({f})" for n, f in not_tracked)
        out.append(
            "Benchmarks that exist in `crates/openquant/benches/` but are not in "
            f"`benchmarks/benchmark_manifest.json`, so are neither committed here nor gated: "
            f"{items}. Run them with `cargo bench -p openquant --bench <file stem>`.\n"
        )

    out.append("## Python data layer\n")
    ds = data.get("dataset", {})
    out.append(
        "`benchmarks/data_processing/latest.json`, written by "
        "`python/benchmarks/benchmark_data_processing.py`: "
        f"{ds.get('symbols', '?')} symbols × {ds.get('rows_per_symbol', 0):,} rows "
        f"({ds.get('total_rows', 0):,} rows), {data.get('iterations', '?')} iterations per "
        "function. The file records neither a date nor a commit. `just py-bench-data` "
        "regenerates it (with 200,000 rows per symbol, not the size committed here).\n"
    )
    rows = [
        "| Function | Rows | Mean (ms) | p95 (ms) | Rows/s | MB/s |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for f in data.get("functions", []):
        rows.append(
            f"| `{f['name']}` | {f['rows']:,} | {fmt_ms(f['mean_ms'])} | {fmt_ms(f['p95_ms'])} | "
            f"{f['rows_per_sec']:,.0f} | {f['mb_per_sec']:,.1f} |"
        )
    out.append("\n".join(rows) + "\n")
    if not (BENCH / "data_processing" / "baseline.json").exists():
        out.append(
            "There is no committed `benchmarks/data_processing/baseline.json`, so "
            "`just py-bench-data-compare` has nothing to compare against until one is made, "
            "and no CI job runs these benchmarks.\n"
        )

    out.append("## Regression gate\n")
    rows = ["| Benchmark | Allowed slowdown |", "| --- | ---: |"]
    for key in manifest:
        rows.append(f"| `{key}` | {overrides.get(key, gate_pct):.0f}% |")
    out.append(
        "`.github/workflows/benchmark-regression.yml` runs on pull requests that touch "
        "`crates/openquant/`, the workspace manifests, the toolchain pin or the benchmark "
        "scripts. It builds the pull request's merge base and its head, runs the "
        "`perf_hotspots` and `synthetic_ticker_pipeline` benches on both **on the same runner**, "
        "and fails if a benchmark's mean slowed down by more than "
        f"{gate_pct:.0f}% (`scripts/check_bench_thresholds.py`), or by more than its entry in "
        "`benchmarks/threshold_overrides.json`. A benchmark that stops producing a result "
        "fails the gate too. Comparing base and head back to back removes the machine-to-"
        "machine variation that made a gate against the committed baseline fail on unrelated "
        "changes. Because the workflow is path-filtered, it is not suitable as a required status check.\n"
    )
    out.append("\n".join(rows) + "\n")
    out.append("## Reproduce\n")
    out.append(
        "```bash\n"
        "just bench-all      # cargo bench -p openquant --bench perf_hotspots --bench synthetic_ticker_pipeline\n"
        "just bench-collect  # target/criterion -> benchmarks/latest_benchmarks.json (manifest only)\n"
        "just bench-check    # latest vs the committed baseline, with the thresholds CI uses\n"
        "just py-bench-data  # Python data-layer benchmarks -> benchmarks/data_processing/latest.json\n"
        f"python3 {SCRIPT} --write   # re-render this page\n"
        "```\n"
    )
    out.append(
        "Refresh `benchmarks/baseline_benchmarks.json` only in a pull request that says why; "
        "a slowdown and a new baseline in the same change hides the slowdown.\n"
    )
    return "\n".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------- changelog


def render_changelog(stamp: str) -> str:
    text = CHANGELOG.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or not lines[0].startswith("# "):
        raise SourceError("CHANGELOG.md must open with a `# ` title")
    body = "\n".join(lines[1:]).strip()
    # Relative links in CHANGELOG.md point into the repository; on the site they
    # have to point at GitHub.
    body = re.sub(
        r"\]\((?!https?://|#|/)([^)]+)\)", lambda m: f"]({REPO_URL}/blob/main/{m.group(1)})", body
    )
    return (
        frontmatter(
            title="Changelog",
            description="Notable changes to OpenQuant, rendered from CHANGELOG.md.",
            generated_from="CHANGELOG.md",
            order=3,
            stamp=stamp,
        )
        + body
        + "\n"
    )


# --------------------------------------------------------------------------- driver


def build_pages(stamp: str) -> dict[Path, str]:
    entries = [notebook_entry(p) for p in sorted(NOTEBOOKS.glob("[0-9][0-9]_*.ipynb"))]
    return {
        DOCS / "runbooks" / "index.md": render_gallery(entries, stamp),
        DOCS / "project" / "performance.md": render_performance(stamp),
        DOCS / "project" / "changelog.md": render_changelog(stamp),
    }


def strip_stamp(text: str) -> str:
    return STAMP_RE.sub("", text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if a page is stale (default)")
    mode.add_argument("--write", action="store_true", help="rewrite stale pages")
    args = parser.parse_args()

    try:
        pages = build_pages(date.today().isoformat())
    except SourceError as err:
        print(f"{SCRIPT}: {err}", file=sys.stderr)
        return 1

    stale = []
    for path, want in pages.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have is not None and strip_stamp(have) == strip_stamp(want):
            continue
        stale.append(path)
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want, encoding="utf-8")

    rel = [str(p.relative_to(ROOT)) for p in stale]
    if args.write:
        print(f"rewrote {len(rel)} page(s)" + (": " + ", ".join(rel) if rel else ""))
        return 0
    if rel:
        print(
            "generated pages are stale: " + ", ".join(rel) + f"\nrun `python3 {SCRIPT} --write`",
            file=sys.stderr,
        )
        return 1
    print(f"generated pages are current ({len(pages)} checked)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
