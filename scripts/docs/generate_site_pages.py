SCRIPT = "scripts/docs/generate_site_pages.py"

STAMP_RE = re.compile(r"^last_generated: .*$", re.MULTILINE)


class SourceError(Exception):
    """A source file does not have the shape this script needs."""


# --------------------------------------------------------------------------- shared


def frontmatter(
    *, title: str, description: str, generated_from: str, order: int, stamp: str
) -> str:
    return (
        "---\n"
        f"title: {json.dumps(title, ensure_ascii=False)}\n"
        f"description: {json.dumps(description, ensure_ascii=False)}\n"
        "status: generated\n"
        f"generated_from: {json.dumps(generated_from)}\n"
        f"last_generated: '{stamp}'\n"
        "audience:\n"
        "  - quant-dev\n"
        "  - platform-engineering\n"
        "sidebar:\n"
        f"  order: {order}\n"
        "---\n\n"
        f"<!-- Generated by {SCRIPT} from {generated_from}. Do not edit by hand:\n"
        f"     change the source and run `python3 {SCRIPT} --write`. -->\n\n"
    )


def figure_pair(name: str, alt: str) -> str:
    alt = alt.replace('"', "&quot;")
    return (
        f'<img class="dark:sl-hidden" src="/figures/notebooks/{name}-light.svg" alt="{alt}" />\n'
        f'<img class="light:sl-hidden" src="/figures/notebooks/{name}-dark.svg" alt="{alt}" />\n'
    )


def fmt_ms(value: float) -> str:
    if value >= 100:
        return f"{value:,.1f}"
    if value >= 1:
        return f"{value:,.2f}"
    return f"{value:,.3f}"


# --------------------------------------------------------------------------- notebooks


def cell_text(cell: dict) -> str:
    src = cell.get("source", "")
    return "".join(src) if isinstance(src, list) else src


def split_sections(cells: list[dict]) -> dict[str, list[dict]]:
    """Cells grouped by the `## ` heading they fall under ('' before the first).

    A markdown cell that opens with `## Name` starts section `Name`; the rest of
    that cell's text belongs to the section (the heading line is dropped).
    """
    sections: dict[str, list[dict]] = {"": []}
    current = ""
    for cell in cells:
        text = cell_text(cell)
        if cell.get("cell_type") == "markdown":
            m = re.match(r"^## (.+?)\s*$", text.splitlines()[0] if text else "")
            if m:
                current = m.group(1).strip()
                rest = "\n".join(text.splitlines()[1:]).strip("\n")
                sections.setdefault(current, [])
                if rest.strip():
                    sections[current].append({**cell, "source": rest})
                continue
        sections.setdefault(current, []).append(cell)
    return sections


def markdown_of(cells: list[dict]) -> str:
    return "\n\n".join(
        cell_text(c).strip() for c in cells if c.get("cell_type") == "markdown"
    ).strip()


def paragraphs(md: str) -> list[str]:
    return [p.strip("\n") for p in re.split(r"\n\s*\n", md) if p.strip()]


def hypothesis_blocks(md: str) -> str:
    """The `**H<n>` paragraphs and list items (with their continuation lines)."""
    lines = md.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        item = re.match(r"^- \*\*H\d", line)
        para = re.match(r"^\*\*H\d", line)
        if item or para:
            block = [line]
            i += 1
            while i < len(lines):
                nxt = lines[i]
                if not nxt.strip():
                    break
                if item and not nxt.startswith((" ", "\t")):
                    break
                block.append(nxt)
                i += 1
            if para and out:
                out.append("")
            out.extend(block)
            continue
        i += 1
    return "\n".join(out).strip()


def stdout_of(cells: list[dict]) -> str:
    chunks = []
    for cell in cells:
        if cell.get("cell_type") != "code":
            continue
        for output in cell.get("outputs", []):
            if output.get("output_type") == "stream" and output.get("name") == "stdout":
                text = output.get("text", "")
                chunks.append("".join(text) if isinstance(text, list) else text)
    return "".join(chunks).rstrip()


def analysis_result(cells: list[dict]) -> tuple[str, str]:
    """('text', verdict printout) or ('markdown', paragraphs)."""
    printed = stdout_of(cells)
    if printed:
        return "text", printed
    paras = paragraphs(markdown_of(cells))
    names_hypothesis = re.compile(r"^\*\*[^*]*(\bH\d|[Hh]ypothes)")
    picked: list[str] = []
    for p in paras:
        if names_hypothesis.match(p):
            picked.append(p)
        elif picked:
            break
    if picked:
        return "markdown", "\n\n".join(picked)
    if paras:
        return "markdown", paras[0]
    raise SourceError("the Analysis section has neither printed output nor prose")


FIGURE_CALL = re.compile(r"""\bfigure\(\s*["']([a-z0-9][a-z0-9-]*)["']""")


def figures_of(cells: list[dict], nb_name: str) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for cell in cells:
        if cell.get("cell_type") != "code":
            continue
        for name in FIGURE_CALL.findall(cell_text(cell)):
            if any(name == n for n, _ in found):
                continue
            light = FIGURES / f"{name}-light.svg"
            dark = FIGURES / f"{name}-dark.svg"
            if not (light.exists() and dark.exists()):
                raise SourceError(
                    f"{nb_name} draws figure {name!r} but {light.relative_to(ROOT)} "
                    f"or its -dark twin is missing; run `just notebooks-run`"
                )
            m = re.search(r"<title>(.*?)</title>", light.read_text(encoding="utf-8"), re.S)
            alt = (m.group(1).strip() if m else "") or name
            alt = alt.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
            found.append((name, " ".join(alt.split())))
    return found


def runbook_page_for(nb_file: str) -> str | None:
    """Slug of the runbook page that links to this notebook, if exactly one does."""
    needle = f"notebooks/python/{nb_file}"
    hits = [
        p
        for p in sorted(RUNBOOK_PAGES.glob("*.md"))
        if p.name != "index.md" and needle in p.read_text(encoding="utf-8")
    ]
    if len(hits) > 1:
        raise SourceError(f"{needle} is referenced by several runbook pages: {hits}")
    return f"/runbooks/{hits[0].stem}/" if hits else None


def notebook_entry(path: Path) -> dict:
    nb = json.loads(path.read_text(encoding="utf-8"))
    cells = nb.get("cells", [])
    if not cells:
        raise SourceError(f"{path.name} has no cells")
    head = cell_text(cells[0])
    m = re.match(r"^# (.+?)\s*$", head.splitlines()[0] if head else "")
    if not m:
        raise SourceError(f"{path.name}: the first cell does not open with a `# ` title")
    title = re.sub(r"^(Runbook|API tour):\s*", "", m.group(1)).strip()
    title = title[0].upper() + title[1:]
    intro = [
        p
        for p in paragraphs("\n".join(head.splitlines()[1:]))
        if not p.startswith(">") and not p.startswith("#")
    ]
    sections = split_sections(cells)
    entry = {
        "file": path.name,
        "number": path.name.split("_", 1)[0],
        "title": title,
        "summary": intro[0] if intro else "",
        "figures": figures_of(cells, path.name),
        "page": runbook_page_for(path.name),
        "runbook": "Hypothesis" in sections and "Promotion decision" in sections,
    }
    if entry["runbook"]:
        hyp_md = markdown_of(sections["Hypothesis"])
        entry["hypothesis"] = hypothesis_blocks(hyp_md) or hyp_md
        if "Analysis" not in sections:
            raise SourceError(f"{path.name} has a Promotion decision but no Analysis section")
        entry["result"] = analysis_result(sections["Analysis"])
        decision = paragraphs(markdown_of(sections["Promotion decision"]))
        if not decision:
            raise SourceError(f"{path.name}: the Promotion decision section is empty")
        entry["decision"] = decision
    return entry


def render_gallery(entries: list[dict], stamp: str) -> str:
    runbooks = [e for e in entries if e["runbook"]]
    others = [e for e in entries if not e["runbook"]]
    nb_url = f"{REPO_URL}/blob/main/notebooks/python"
    out = [
        frontmatter(
            title="Research gallery",
            description=(
                "Every research runbook in notebooks/python: its pre-registered hypothesis, "
                "figures, result and promotion decision, taken from the executed notebooks."
            ),
            generated_from="notebooks/python/*.ipynb",
            order=0,
            stamp=stamp,
        )
    ]
    out.append(
        ":::caution[SYNTHETIC data]\n"
        "Every committed result on this page is computed on simulated series or on the committed "
        "SYNTHETIC sample `SYN_A`..`SYN_E` (see `DATA_SOURCES.md`). None of it describes a real "
        "market.\n"
        ":::\n"
    )
    out.append(
        "A runbook is a notebook that states a falsifiable hypothesis before it is run, tests it "
        "on data where the right answer is known, and ends with a promotion decision: what, if "
        "anything, later work should adopt. The notebooks are executed in CI "
        "(`.github/workflows/notebooks.yml`) and committed with their outputs, and this page is "
        "rebuilt from those outputs, so each result below is the text the notebook printed or "
        "wrote on its last committed run. The hypotheses are quoted in part (the `H1`, `H2`, ... "
        "statements); each runbook's page and notebook have the full pre-registration, the method "
        "and the controls.\n"
    )
    rows = ["| # | Runbook | Figures | Decision |", "| --- | --- | ---: | --- |"]
    for e in runbooks:
        link = e["page"] or f"{nb_url}/{e['file']}"
        lead = re.match(r"^\*\*(.+?)\*\*", e["decision"][0], re.S)
        verdict = lead.group(1).rstrip(".") if lead else e["decision"][0].split(". ")[0]
        verdict = " ".join(verdict.split())
        verdict = re.sub(r"^Decision:\s*", "", verdict)
        verdict = verdict[0].upper() + verdict[1:]
        rows.append(f"| {e['number']} | [{e['title']}]({link}) | {len(e['figures'])} | {verdict} |")
    out.append("\n".join(rows) + "\n")

    for e in runbooks:
        out.append(f"## {e['number']} · {e['title']}\n")
        links = []
        if e["page"]:
            links.append(f"[Runbook page]({e['page']})")
        links.append(f"[notebook `{e['file']}`]({nb_url}/{e['file']})")
        out.append(" · ".join(links) + "\n")
        out.append("### Hypothesis\n")
        out.append(e["hypothesis"] + "\n")
        for name, alt in e["figures"]:
            out.append(figure_pair(name, alt))
        out.append("### Result\n")
        kind, body = e["result"]
        if kind == "text":
            out.append("As printed by the notebook's Analysis section:\n")
            out.append("```text\n" + body + "\n```\n")
        else:
            out.append(body + "\n")
        out.append("### Promotion decision\n")
        out.append(e["decision"][0] + "\n")
        if len(e["decision"]) > 1:
            out.append("<details>\n<summary>The rest of the decision</summary>\n")
            out.append("\n\n".join(e["decision"][1:]) + "\n")
            out.append("</details>\n")

    if others:
        out.append("## API tours\n")
        out.append(
            "These notebooks have no pre-registered hypothesis and promotion decision, so they are "
            "not runbooks: they show how a few calls fit together on synthetic data and claim "
            "nothing (see the [notebook contract](/workflows/research-notebook-contract/)). They "
            "are executed and checked in CI in the same way.\n"
        )
        for e in others:
            out.append(f"### {e['number']} · {e['title']}\n")
            out.append(f"[notebook `{e['file']}`]({nb_url}/{e['file']})\n")
            if e["summary"]:
                out.append(e["summary"] + "\n")
            for name, alt in e["figures"]:
                out.append(figure_pair(name, alt))
    return "\n".join(out).rstrip() + "\n"


