#!/usr/bin/env python3
"""Generate the docs-site pages whose content lives elsewhere in the repository.

Three pages are rendered from files that are already the source of truth, so
that the site cannot drift from them:

  runbooks/index.md       the research gallery, from the executed notebooks in
                          notebooks/python/NN_*.ipynb and the figures they export
                          to docs-site/public/figures/notebooks/
  project/performance.md  from benchmarks/*.json, benchmarks/data_processing/latest.json
                          and the criterion benches in crates/openquant/benches/
  project/changelog.md    from CHANGELOG.md

Modes:

  --check (default, CI)  exit non-zero if any page differs from what the sources give
  --write                rewrite the pages that differ

Every page carries `status: generated` and a `last_generated` stamp. The stamp is
ignored when comparing, and a page whose content has not changed keeps its old
stamp, so re-running this script is a no-op unless a source moved.

What the gallery reads from a notebook (the runbook sections of the notebook
contract, see notebooks/python/README.md):

  title       the first `# ` heading, without a leading "Runbook: " or "API tour: "
  hypothesis  the `## Hypothesis` section: its `**H1 ...**` paragraphs and bullets
              (the whole section when there are none)
  figures     every `figure("nbNN-...")` call in a code cell, alt text from the
              exported SVG's <title>
  result      the stdout of the code cells under `## Analysis` (the executed
              verdict); if there is none, the Analysis paragraphs whose bold lead
              names a hypothesis (`**H1 ...**`, `**Both hypotheses ...**`); failing
              that, the first Analysis paragraph
  decision    the `## Promotion decision` section

A notebook with both a Hypothesis and a Promotion decision section is listed as a
runbook; the others are listed below them with their summary paragraph and figures.
Standard library only, so it runs on the CI runner's python3.
"""

