#!/usr/bin/env node
/**
 * check:python-examples — run every Python block in the docs against the real
 * `openquant` package.
 *
 * The sibling gate (check-doc-examples.mjs) compiles the ```rust blocks on the
 * generated module pages. Nothing ever checked the ```python blocks, even
 * though Python is what a new user actually runs — quickstart Step 5 is Python.
 * Two defects shipped because of that hole: a quickstart comment asserting
 * `'promote_candidate': True` for a call whose real answer is False, and four
 * documented `mda_importance` call sites left raising after `event_end_indices`
 * became required. Both would have been caught here.
 *
 * Unlike the Rust gate this one EXECUTES: a Python call site has no compiler,
 * so importing the module and running the snippet is the only way to prove the
 * function exists, takes those keyword arguments and returns those keys.
 *
 * Not every snippet can run. Some are deliberately illustrative — they contain
 * `...` placeholders, read a `trades.parquet` nobody ships, or continue a
 * variable defined in the prose above them. A gate that fails on those is a
 * gate somebody disables, so they opt out explicitly, and:
 *
 *   - the opt-out is per-fence and visible in source: ```python doc-check=skip
 *     (from src/data/moduleDocs.ts, set `docCheck: "skip"` on the example);
 *   - every skip is printed by name on every run, so skipping cannot hide;
 *   - skipped blocks are still parsed with ast.parse, so an unrunnable snippet
 *     is at least valid Python, not a typo nobody will ever notice.
 *
 * Each block runs in its own interpreter — blocks are independent, exactly as
 * the Rust gate treats each fence as its own module. A snippet that only makes
 * sense as a continuation of the one above it is a skip candidate.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const docsSite = path.resolve(here, '..');
const repoRoot = path.resolve(docsSite, '..');
const pagesRoot = path.join(docsSite, 'src/content/docs');
const outDir = path.join(repoRoot, 'target/doc-python-examples');

const PER_BLOCK_TIMEOUT_MS = Number(process.env.DOC_PYTHON_TIMEOUT_MS ?? 180_000);

// --- 1. Extract every ```python fence from every docs page ------------------
// Both the generated module pages and the hand-written guides: the quickstart
// and the workflow walk-through are exactly the pages a newcomer copies from.

const PY_FENCE = /^```python[^\S\n]*([^\n]*)\n([\s\S]*?)^```[^\S\n]*$/gm;
const SKIP_COMMENT = /^\s*#\s*doc-check:\s*skip\b[^\n]*/im;

const walkPages = (dir) => {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkPages(full));
    else if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) out.push(full);
  }
  return out;
};

const blocks = [];
for (const file of walkPages(pagesRoot)) {
  const page = path.relative(pagesRoot, file);
  const text = fs.readFileSync(file, 'utf8');
  let m;
  let n = 0;
  while ((m = PY_FENCE.exec(text)) !== null) {
    const meta = m[1].trim();
    const code = m[2].replace(/\s+$/, '');
    const commentSkip = SKIP_COMMENT.exec(code);
    const skip = /(^|\s)doc-check=skip(\s|$)/.test(meta) || Boolean(commentSkip);
    const reason = (meta.match(/(^|\s)doc-check-reason="([^"]*)"/)?.[2] ?? commentSkip?.[0]?.replace(/^\s*#\s*doc-check:\s*skip\b[\s:—-]*/i, '') ?? '').trim();
    blocks.push({ page, index: n++, code, skip, reason });
  }
}

if (blocks.length === 0) {
  console.error(`check:python-examples: no python blocks found under ${pagesRoot}.`);
  console.error('If the module pages are missing, run `node scripts/generate-module-doc-pages.mjs` first.');
  process.exit(1);
}

// --- 2. Materialise one .py file per block ----------------------------------

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const nameOf = (b) => `ex_${b.page.replace(/\.(md|mdx)$/, '').replace(/[^a-z0-9]+/gi, '_')}_${b.index}.py`;
for (const b of blocks) {
  b.file = path.join(outDir, nameOf(b));
  fs.writeFileSync(
    b.file,
    `# GENERATED by docs-site/scripts/check-doc-python-examples.mjs — do not edit.\n` +
      `# Source: docs-site/src/content/docs/${b.page} — python block #${b.index}` +
      `${b.skip ? ' (doc-check=skip: syntax-checked only)' : ''}\n${b.code}\n`,
    'utf8'
  );
}

// --- 3. Pick an interpreter that can import openquant -----------------------

const candidates = [
  process.env.DOC_PYTHON,
  path.join(repoRoot, '.venv/bin/python3'),
  path.join(repoRoot, '.venv/bin/python'),
  'python3',
].filter(Boolean);

// The worktree's own python/ sources come first so the gate checks this tree,
// not whatever wheel happens to be installed in the environment. Only when the
// compiled extension actually sits beside them, though: `maturin develop`
// normally drops _core there, but if it has not, shadowing the installed
// package with a source tree that has no _core turns a working environment
// into an unimportable one.
const localPackage = path.join(repoRoot, 'python');
const hasLocalExtension = fs
  .readdirSync(path.join(localPackage, 'openquant'), { withFileTypes: true })
  .some((e) => e.isFile() && /^_core.*\.(so|pyd|dylib)$/.test(e.name));
const pythonPath = [hasLocalExtension ? localPackage : null, process.env.PYTHONPATH]
  .filter(Boolean)
  .join(path.delimiter);
const runEnv = { ...process.env, PYTHONPATH: pythonPath, PYTHONDONTWRITEBYTECODE: '1' };

let python = null;
for (const candidate of candidates) {
  const probe = spawnSync(candidate, ['-c', 'import openquant'], { env: runEnv, encoding: 'utf8' });
  if (!probe.error && probe.status === 0) {
    python = candidate;
    break;
  }
}

if (!python) {
  console.error('check:python-examples: no interpreter could `import openquant`.');
  console.error(`Tried: ${candidates.join(', ')}`);
  console.error('Build the extension first, e.g. `maturin develop --release` in a venv,');
  console.error('or point DOC_PYTHON at an interpreter that already has it.');
  process.exit(1);
}

// --- 4. Syntax-check EVERY block, skipped ones included ---------------------

const syntaxCheck = spawnSync(
  python,
  [
    '-c',
    'import ast,sys\n' +
      'bad=0\n' +
      'for p in sys.argv[1:]:\n' +
      '    src=open(p,encoding="utf-8").read()\n' +
      '    try:\n' +
      '        ast.parse(src, filename=p)\n' +
      '    except SyntaxError as e:\n' +
      '        bad+=1\n' +
      '        print(f"{p}:{e.lineno}: {e.msg}", file=sys.stderr)\n' +
      'sys.exit(1 if bad else 0)',
    ...blocks.map((b) => b.file),
  ],
  { env: runEnv, encoding: 'utf8' }
);

if (syntaxCheck.status !== 0) {
  console.error('');
  console.error('check:python-examples: FAILED — a documented Python block is not valid Python.');
  console.error(syntaxCheck.stderr.trim());
  console.error('This check runs on skipped blocks too: `doc-check=skip` excuses a snippet from');
  console.error('running, never from parsing.');
  process.exit(1);
}

// --- 5. Execute the runnable ones -------------------------------------------

const runnable = blocks.filter((b) => !b.skip);
const skipped = blocks.filter((b) => b.skip);
const pageCount = new Set(blocks.map((b) => b.page)).size;

console.log(
  `check:python-examples: ${blocks.length} python block(s) on ${pageCount} page(s) — ` +
    `running ${runnable.length}, syntax-checking ${skipped.length} skipped, via ${python}.`
);

const failures = [];
for (const b of runnable) {
  // cwd is the repo root so that documented relative paths such as
  // python/tests/fixtures/ohlcv_us_equities.csv resolve the way a reader
  // running the snippet from a fresh clone would see them resolve.
  const run = spawnSync(python, [b.file], {
    cwd: repoRoot,
    env: runEnv,
    encoding: 'utf8',
    timeout: PER_BLOCK_TIMEOUT_MS,
    maxBuffer: 32 * 1024 * 1024,
  });
  const label = `${b.page} block #${b.index}`;
  if (run.error?.code === 'ETIMEDOUT' || run.signal === 'SIGTERM') {
    failures.push({ label, file: b.file, detail: `timed out after ${PER_BLOCK_TIMEOUT_MS} ms` });
    console.log(`  TIMEOUT  ${label}`);
  } else if (run.status !== 0) {
    failures.push({ label, file: b.file, detail: (run.stderr || run.stdout || '').trim() });
    console.log(`  FAIL     ${label}`);
  } else {
    console.log(`  ok       ${label}`);
  }
}

// Print every skip on every run. A silent skip list is how a gate quietly
// stops gating anything.
if (skipped.length) {
  console.log(`check:python-examples: skipped (syntax-checked only), ${skipped.length}:`);
  for (const b of skipped) {
    console.log(`  skip     ${b.page} block #${b.index}${b.reason ? ` — ${b.reason}` : ''}`);
  }
}

if (failures.length) {
  for (const f of failures) {
    console.error('');
    console.error(`check:python-examples: ${f.label} FAILED`);
    console.error(`  generated file: ${f.file}`);
    console.error(
      f.detail
        .split('\n')
        .map((line) => `  ${line}`)
        .join('\n')
    );
  }
  console.error('');
  console.error(`check:python-examples: FAILED — ${failures.length} of ${runnable.length} documented Python example(s) do not run.`);
  console.error('Fix the example at its source: module pages come from docs-site/src/data/moduleDocs.ts');
  console.error('(the .md is overwritten by generate-module-doc-pages.mjs); every other page is edited');
  console.error('directly. If a snippet is genuinely illustrative, mark the fence ```python doc-check=skip');
  console.error('(or set docCheck: "skip" on the moduleDocs example) — it is then still parsed, not run.');
  process.exit(1);
}

console.log(
  `check:python-examples: OK — ${runnable.length} documented Python example(s) ran clean, ` +
    `${skipped.length} skipped but parsed.`
);
