#!/usr/bin/env node
/**
 * check:examples — compile Rust blocks on module pages and the runnable workflow.
 *
 * The module pages under src/content/docs/modules/ are emitted from
 * src/data/moduleDocs.ts, and their `### Rust` usage examples were historically
 * written against a symbol's *name* without ever being checked against that
 * symbol's *signature*. This gate closes that hole: it extracts every ```rust
 * fence from those pages, wraps each one in a closure inside a throwaway crate
 * that depends on the real `openquant` crate by path, and runs `cargo check`.
 * A wrong arity, a missing receiver, a renamed method or a wrong argument type
 * is a compile error, so it fails here instead of shipping.
 *
 * Compile-only by design: the snippets are never executed (several of them read
 * files or spawn threads), so this proves the API surface is real, not that the
 * numbers are right.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const docsSite = path.resolve(here, '..');
const repoRoot = path.resolve(docsSite, '..');
const pagesDir = path.join(docsSite, 'src/content/docs/modules');
const crateSrc = path.join(repoRoot, 'crates/openquant/src');
const outDir = path.join(repoRoot, 'target/doc-examples');

// --- 1. Extract module examples and the complete runnable workflow ----------

const RUST_FENCE = /^```rust\n([\s\S]*?)^```$/gm;

const pages = fs.readdirSync(pagesDir).filter((f) => f.endsWith('.md')).sort()
  .map((file) => ({ file: path.join(pagesDir, file), page: `modules/${file}`, standalone: false }));
pages.push({
  file: path.join(docsSite, 'src/content/docs/workflows/rust-core-workflow.md'),
  page: 'workflows/rust-core-workflow.md',
  standalone: true,
});
const blocks = [];
for (const { file, page, standalone } of pages) {
  const text = fs.readFileSync(file, 'utf8');
  const slug = page.replace(/\.md$/, '');
  let m;
  let n = 0;
  while ((m = RUST_FENCE.exec(text)) !== null) {
    blocks.push({ slug, page, standalone, index: n++, code: m[1].replace(/\s+$/, '') });
  }
}

if (blocks.length === 0) {
  console.error(`check:examples: no rust blocks found under ${pagesDir}.`);
  console.error('Run `node scripts/generate-module-doc-pages.mjs` from inside docs-site/ first.');
  process.exit(1);
}

// --- 2. Discover the crate's error enums so `?` can be propagated -----------
// The openquant error types mostly do not implement std::error::Error, so
// Box<dyn Error> is not available as a universal `?` target. Instead we collect
// every `pub enum *Error` in the crate and generate a From impl into one local
// DocError. Discovering them keeps the gate working when a module is added.

const errorTypes = ['String', "&'static str", 'std::io::Error', 'chrono::ParseError'];
const walk = (dir, prefix = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, [...prefix, entry.name]);
    } else if (entry.name.endsWith('.rs') && entry.name !== 'lib.rs' && entry.name !== 'mod.rs') {
      const mod = [...prefix, entry.name.replace(/\.rs$/, '')].join('::');
      for (const m of fs.readFileSync(full, 'utf8').matchAll(/^pub enum (\w*Error)\b/gm)) {
        errorTypes.push(`openquant::${mod}::${m[1]}`);
      }
    }
  }
};
walk(crateSrc);

// --- 3. Emit a throwaway crate ---------------------------------------------

// The snippets pass nalgebra/itertools/chrono values into `openquant`, so the scratch
// crate must resolve the same major versions as `openquant` itself or every such call is
// a type mismatch. Read the requirements from its manifest rather than pinning them here,
// so a dependency bump there (e.g. a Dependabot PR) cannot drift from this gate.
const openquantManifest = fs.readFileSync(path.join(repoRoot, 'crates/openquant/Cargo.toml'), 'utf8');
const depsSection = openquantManifest.split(/^\[dependencies\]$/m)[1].split(/^\[/m)[0];
function openquantDep(name) {
  const m = depsSection.match(new RegExp(`^${name}\\s*=\\s*(?:"([^"]+)"|\\{[^}]*version\\s*=\\s*"([^"]+)")`, 'm'));
  if (!m) {
    console.error(`check:examples: no \`${name}\` in [dependencies] of crates/openquant/Cargo.toml`);
    process.exit(1);
  }
  return m[1] ?? m[2];
}

fs.mkdirSync(path.join(outDir, 'src'), { recursive: true });

fs.writeFileSync(
  path.join(outDir, 'Cargo.toml'),
  `# GENERATED by docs-site/scripts/check-doc-examples.mjs — do not edit.
[workspace]

[package]
name = "openquant-doc-examples"
version = "0.0.0"
edition = "2024"
publish = false

[dependencies]
openquant = { path = ${JSON.stringify(path.join(repoRoot, 'crates/openquant'))} }
chrono = "${openquantDep('chrono')}"
nalgebra = "${openquantDep('nalgebra')}"
itertools = "${openquantDep('itertools')}"
`,
  'utf8'
);

const modules = blocks.map(({ slug, page, standalone, index, code }) => {
  const name = `ex_${slug.replace(/[^a-z0-9]+/gi, '_')}_${index}`;
  if (standalone) {
    // A complete program has its own imports/main and can begin with //! docs.
    // Compile it as a module; wrapping it in a statement closure is not valid.
    const body = code.split('\n').map((line) => line ? `    ${line}` : '').join('\n');
    return `// docs-site/src/content/docs/${page} — rust block #${index}
mod ${name} {
${body}
}`;
  }
  const body = code
    .split('\n')
    .map((line) => (line ? `            ${line}` : ''))
    .join('\n');
  return `// docs-site/src/content/docs/${page} — rust block #${index}
mod ${name} {
    use super::DocError;
    pub fn example() {
        let _ = || -> Result<(), DocError> {
${body}
            Ok(())
        };
    }
}`;
});

fs.writeFileSync(
  path.join(outDir, 'src/lib.rs'),
  `// GENERATED by docs-site/scripts/check-doc-examples.mjs — do not edit.
// One module per documented Rust block; complete programs retain their own scope.
#![allow(unused_imports, unused_variables, unused_mut, dead_code, unused_braces, clippy::all)]

#[derive(Debug)]
pub struct DocError(pub String);

macro_rules! doc_error_from {
    ($($t:ty),* $(,)?) => {
        $(impl From<$t> for DocError {
            fn from(e: $t) -> Self { DocError(format!("{e:?}")) }
        })*
    };
}
doc_error_from!(${[...new Set(errorTypes)].join(', ')});

${modules.join('\n\n')}
`,
  'utf8'
);

// --- 4. cargo check ---------------------------------------------------------

console.log(`check:examples: compiling ${blocks.length} rust example(s) from ${new Set(blocks.map((b) => b.slug)).size} documentation page(s)…`);

const result = spawnSync(
  'cargo',
  ['check', '--quiet', '--manifest-path', path.join(outDir, 'Cargo.toml')],
  {
    stdio: 'inherit',
    // Reuse an explicitly managed cache, or share the workspace target by default.
    env: { ...process.env, CARGO_TARGET_DIR: process.env.CARGO_TARGET_DIR || path.join(repoRoot, 'target') },
  }
);

if (result.error) {
  console.error(`check:examples: could not run cargo (${result.error.message}).`);
  console.error('A Rust toolchain is required; install one with https://rustup.rs.');
  process.exit(1);
}

if (result.status !== 0) {
  console.error('');
  console.error('check:examples: FAILED — at least one documented Rust example does not compile.');
  console.error(`Generated crate for inspection: ${outDir}/src/lib.rs`);
  console.error('Fix the example directly in its authored page under docs-site/src/content/docs/.');
  process.exit(result.status ?? 1);
}

console.log(`check:examples: OK — all ${blocks.length} documented Rust examples compile.`);
